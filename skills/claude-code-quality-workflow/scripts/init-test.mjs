#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const scripts = resolve(process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '../.claude/quality-workflow/scripts'));
const engine = process.argv[3] || 'claude';
const {inventory, selectValidation, savePlan} = await import(pathToFileURL(join(scripts, 'quality-init.mjs')));
const dir = mkdtempSync(join(tmpdir(), 'quality-init-test-'));
const repo = join(dir, 'repo with spaces'), workflow = dirname(scripts);
mkdirSync(repo);
const save = (name, value) => {const p = join(repo, name); mkdirSync(dirname(p), {recursive:true}); writeFileSync(p, value);};
function run(bin, args, cwd = repo, expected = 0) {
  const result = spawnSync(bin, args, {cwd, encoding:'utf8', maxBuffer:16*1024*1024});
  assert.equal(result.status, expected, result.stdout + result.stderr);
  return result.stdout.trim();
}
const git = (...args) => run('git', args);
git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
save('package.json', JSON.stringify({private:true, scripts:{'check:unit':'node --test packages/unit/case.test.mjs', deploy:'exit 99'}}));
save('packages/unit/package.json', JSON.stringify({scripts:{test:'node --test case.test.mjs'}}));
save('packages/unit/case.test.mjs', "import {test} from 'node:test'; test('fixture', () => {});\n");
save('.github/workflows/ci.yml', 'name: CI\njobs:\n  test:\n    steps:\n      - run: npm run check:unit\n');
git('add', '.'); git('commit', '-m', 'base');
assert.equal(selectValidation(repo, workflow, engine).status, 'NEEDS_INIT');
const scan = inventory(repo);
assert.equal(scan.manifests.length, 2, 'nested manifests discovered without root test');
assert.ok(!existsSync(join(repo,'.git/quality-workflow-init')), 'discovery is read-only');
const gate = command => ({name:command, command, source:'package.json', reason:'fixture gate', safety:'local-validation'});
const plan = {fingerprint:scan.fingerprint, sources:['package.json','.github/workflows/ci.yml'], gates:[gate("node -e 'process.stdin.resume()'"), gate('npm run check:unit')], exclusions:[{name:'Install',source:'CI',reason:'Fresh dependency install remains CI-only'}]};
const selected = savePlan(repo, workflow, engine, plan);
assert.equal(selected.status,'READY');
assert.equal(git('status','--porcelain'),'','setup does not dirty worktree');
assert.equal(savePlan(repo, workflow, engine, plan).path,selected.path,'idempotent command path');
assert.equal(selectValidation(repo,workflow,engine === 'codex' ? 'claude':'codex').path,selected.path,'adapters share init');
const verified = run('bash',[join(scripts,'verify.sh'),'full']);
assert.match(verified,/3 gates/,'stdin-reading gate cannot swallow subsequent commands');
git('switch','-c','feature'); save('feature.txt','change\n'); git('add','.'); git('commit','-m','feature');
run('bash',[join(scripts,'freeze.sh')]);
run('bash',[join(scripts,'prepare-review.sh'),'initial']);
const env = readFileSync(join(repo,`.git/${engine}-quality-workflow/current-evidence.env`),'utf8');
const evidenceDir = env.split('\n').find(line=>line.startsWith('EVIDENCE_DIR=')).slice(13);
const manifest = JSON.parse(readFileSync(join(evidenceDir,'manifest.json'),'utf8'));
assert.equal(manifest.validation.configured,true);
assert.equal(manifest.validation.configuration.origin,'local-init');
assert.match(manifest.warnings.join('\n'),/Fresh dependency install/);
save('.github/workflows/ci.yml', 'changed: gate\n');
assert.throws(()=>selectValidation(repo,workflow,engine),/STALE_INIT/);
run('bash',[join(scripts,'verify.sh'),'full'],repo,1);
assert.throws(()=>savePlan(repo,workflow,engine,plan),/Discovery changed/);
const fresh = {...plan, fingerprint:inventory(repo).fingerprint};
assert.throws(()=>savePlan(repo,workflow,engine,{...fresh,gates:[]}),/real local gate/);
assert.throws(()=>savePlan(repo,workflow,engine,{...fresh,gates:[gate('npm publish')]}),/non-mutating/);
assert.throws(()=>savePlan(repo,workflow,engine,{...fresh,gates:[gate('echo x\nexit 0')]}),/single-line/);
savePlan(repo,workflow,engine,fresh);
writeFileSync(selected.path, 'true\n');
assert.throws(()=>selectValidation(repo,workflow,engine),/INVALID_INIT/);
savePlan(repo,workflow,engine,fresh);
savePlan(repo,workflow,engine,{...fresh,gates:[gate('node -e "process.exit(7)"')]});
run('bash',[join(scripts,'verify.sh'),'full'],repo,7);
savePlan(repo,workflow,engine,fresh);
const explicit = `.${engine}/quality-workflow/validation.commands`;
save(explicit, '# empty user file\n');
assert.throws(()=>selectValidation(repo,workflow,engine),/empty/);
assert.throws(()=>savePlan(repo,workflow,engine,fresh),/already exists/);
save(explicit,'test -f feature.txt\n');
assert.equal(selectValidation(repo,workflow,engine).origin,'repository');
assert.equal(readFileSync(join(repo,explicit),'utf8'),'test -f feature.txt\n');
// Linked worktrees have a .git file; init must use git's resolved metadata path.
const linked = join(dir,'linked worktree');
git('worktree','add','-b','linked',linked,'main');
const linkedPlan = {...plan,fingerprint:inventory(linked).fingerprint};
assert.equal(savePlan(linked,workflow,engine,linkedPlan).status,'READY');
assert.equal(run('git',['status','--porcelain'],linked),'');
console.log(`init integration tests passed (${engine}): discovery, save, verification, evidence, refresh, precedence, safety tripwires, worktrees`);
